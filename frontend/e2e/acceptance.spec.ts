import { test, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'

test('recorrido real: 2FA, parcela, worker FLAIR, CSV, comparación, revisión y exportación',async({page,request})=>{
  test.setTimeout(240000)
  await page.goto('/')
  await expect(page.getByText('Bienvenido a GeoPadrones')).toBeVisible()
  await expect(page.getByLabel('Resultado del captcha')).toBeEnabled()
  await page.screenshot({path:'../artifacts/screenshots/login.png',fullPage:true})
  await page.getByLabel('Correo electrónico').fill('browser-test@example.org')
  await page.getByLabel('Contraseña',{exact:true}).fill('Disposable-browser-test-only-2026')
  const operands=(await page.locator('#captcha-question').innerText()).match(/\d+/g)!.map(Number)
  await page.getByLabel('Resultado del captcha').fill(String(operands[0]+operands[1]))
  await page.getByRole('button',{name:'Ingresar a la plataforma'}).click()
  await expect(page.getByLabel('Código de verificación')).toBeVisible()
  const messages=await request.get('http://127.0.0.1:8125/api/v1/messages')
  const inbox=await messages.json()
  const entry=inbox.messages.find((m:{To:{Address:string}[]})=>m.To.some(t=>t.Address==='browser-test@example.org'))
  expect(entry).toBeTruthy()
  const message=await(await request.get(`http://127.0.0.1:8125/api/v1/message/${entry.ID}`)).json()
  const code=message.Text.match(/\b\d{6}\b/)[0]
  await page.getByLabel('Código de verificación').fill(code)
  await page.getByRole('button',{name:'Verificar e ingresar'}).click()
  await expect(page.getByRole('heading',{name:/Explorador catastral/})).toBeVisible()
  await page.getByLabel('Localidad',{exact:true}).selectOption({label:'MINAS'})
  const api=page.request
  const getJson=async(path:string)=>(await(await api.get('/api/v1'+path)).json())
  const parcels=await getJson('/parcels?limit=100')
  expect(parcels.items.length).toBeGreaterThan(0)
  const parcel=parcels.items.find((p:{m2_parcela:number})=>p.m2_parcela>150&&p.m2_parcela<1000)||parcels.items[0]
  const latencies:number[]=[]
  for(let group=0;group<5;group++)await Promise.all(Array.from({length:8},async()=>{const start=Date.now();const response=await api.get('/api/v1/parcels?limit=50');expect(response.status()).toBe(200);latencies.push(Date.now()-start)}))
  latencies.sort((a,b)=>a-b)
  await mkdir('../artifacts/tests',{recursive:true})
  await writeFile('../artifacts/tests/http-load.json',JSON.stringify({scope:'Disposable QA database; 201 real geometries; Flask threaded development server via Vite; not a production capacity certification',requests:40,concurrency:8,errors:0,p50_ms:latencies[19],p95_ms:latencies[37]},null,2))
  await expect(page.getByRole('button',{name:`Enfocar padrón ${parcel.padron}`,exact:true}).first()).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:'Selección',exact:true}).click()
  const map=page.locator('.map-stage .leaflet-container')
  const bounds=(await map.boundingBox())!
  await map.click({position:{x:bounds.width*.4,y:bounds.height*.4}})
  await map.click({position:{x:bounds.width*.6,y:bounds.height*.4}})
  await map.click({position:{x:bounds.width*.6,y:bounds.height*.6}})
  await map.dblclick({position:{x:bounds.width*.4,y:bounds.height*.6}})
  await expect(page.getByRole('button',{name:'Limpiar selección'})).toBeVisible()
  await page.getByRole('button',{name:'Limpiar selección'}).click()
  await page.getByLabel('Buscar padrón').fill(parcel.padron)
  await page.getByLabel('Buscar padrón').press('Enter')
  await expect(page.getByText(`${parcel.padron}`,{exact:true}).first()).toBeVisible()
  await page.getByRole('button',{name:`Seleccionar padrón ${parcel.padron}`,exact:true}).first().click()
  await page.getByRole('button',{name:'Analizar selección',exact:true}).click()
  await page.getByRole('button',{name:'Iniciar análisis',exact:true}).click()
  await expect(page.getByText('Análisis enviado al worker')).toBeVisible()
  await expect.poll(async()=>{const jobs=await getJson('/analysis/jobs?kind=analysis');return jobs.items[0]?.status},{timeout:150000,intervals:[2000]}).toBe('COMPLETED')
  const detail=await getJson(`/parcels/${parcel.id}`)
  expect(detail.parcel.properties.state).not.toBe('ERROR_ANALISIS')
  expect(detail.parcel.properties.m2_huella_detectada).toBeGreaterThan(0)
  expect(detail.footprints.length).toBeGreaterThan(0)
  expect(detail.evidence.captured_at).toBe('2025-12')
  const maskInfo=await getJson(`/analysis/results/${detail.parcel.properties.result_id}/overlay.json`)
  expect(maskInfo.bounds).toHaveLength(4)
  const maskImage=await api.get(maskInfo.url)
  expect(maskImage.status()).toBe(200)
  expect(maskImage.headers()['content-type']).toContain('image/png')
  await page.reload()
  await expect(page.getByRole('heading',{name:/Explorador catastral/})).toBeVisible()
  await page.getByLabel('Buscar padrón').fill(parcel.padron)
  await page.getByLabel('Buscar padrón').press('Enter')
  await page.getByRole('button',{name:`Enfocar padrón ${parcel.padron}`,exact:true}).first().click()
  await expect(page.getByRole('heading',{name:new RegExp(`Padrón ${parcel.padron}`)})).toBeVisible()
  await expect.poll(()=>page.locator('img.leaflet-tile[src*="/imagery/scenes/"]').evaluateAll(nodes=>nodes.some(node=>(node as HTMLImageElement).complete&&(node as HTMLImageElement).naturalWidth>0)),{timeout:30000}).toBe(true)
  await page.getByRole('checkbox',{name:'Máscara IA del padrón activo'}).check()
  await page.getByLabel('Superficie mínima').fill('1')
  await page.getByRole('button',{name:'Guardar vista',exact:true}).click()
  await page.getByLabel('Nombre de la vista').fill('Minas · vista QA real')
  await page.getByRole('button',{name:'Guardar vista actual',exact:true}).click()
  await expect(page.getByRole('button',{name:'Restaurar vista Minas · vista QA real',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Cerrar vistas'}).click()
  await expect(page.getByRole('button',{name:`Enfocar padrón ${parcel.padron}`,exact:true}).first()).toBeVisible()
  await page.locator('.layers-body').evaluate(el=>{el.scrollTop=0})
  await page.screenshot({path:'../artifacts/screenshots/explorer.png',fullPage:true})
  await page.getByRole('link',{name:'Importaciones CSV',exact:true}).click()
  const csv=Buffer.from(`coddepto;codloccat;padron;construido;observaciones\n${parcel.coddepto};${parcel.codloccat};${parcel.padron};NO;Declaración sintética exclusivamente para probar la comparación contra inferencia real\n`)
  await page.locator('input[type=file]').setInputFiles({name:'declaracion-QA-SINTETICA.csv',mimeType:'text/csv',buffer:csv})
  await expect(page.getByText('Relacioná las columnas')).toBeVisible()
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByRole('button',{name:'Validar correspondencia',exact:true}).click()
  await expect(page.getByText('Revisá la conciliación de la muestra')).toBeVisible()
  await page.getByRole('button',{name:'Confirmar importación',exact:true}).click()
  await expect.poll(async()=>{const rows=await getJson('/imports');return rows.items[0]?.status},{timeout:30000,intervals:[1000]}).toBe('CONFIRMED')
  await page.reload()
  await page.getByRole('button',{name:'Comparar',exact:true}).first().click()
  await expect(page.getByRole('heading',{name:'Comparar declaraciones.'})).toBeVisible()
  await expect.poll(async()=>{const rows=await getJson('/comparisons');const result=await getJson(`/comparisons/${rows.items[0]?.id}`);return result.items[0]?.state},{timeout:30000,intervals:[1000]}).toBe('POSIBLE_CONSTRUCCION_NO_DECLARADA')
  const comparisonRun=(await getJson('/comparisons')).items[0].id
  await expect(page.getByRole('cell',{name:'Posible construcción no declarada',exact:true})).toBeVisible({timeout:15000})
  await page.screenshot({path:'../artifacts/screenshots/comparisons.png',fullPage:true})
  await page.getByRole('button',{name:`Ver padrón ${parcel.padron} en mapa`}).click()
  await expect(page.getByLabel('Modo temático')).toHaveValue('comparison')
  await expect(page.getByRole('heading',{name:new RegExp(`Padrón ${parcel.padron}`)})).toBeVisible()
  await page.getByRole('link',{name:'Casos para revisar',exact:true}).click()
  await page.getByRole('button',{name:new RegExp(`Padrón ${parcel.padron}`)}).first().click()
  await page.getByLabel('Observaciones y motivo').fill('Validación QA de flujo; no constituye etiquetado independiente de precisión local.')
  await page.getByLabel('Adjuntar evidencia').setInputFiles({name:'evidencia-QA-del-benchmark-real.png',mimeType:'image/png',buffer:await(await import('node:fs/promises')).readFile('../artifacts/benchmark/ortho.png')})
  await page.getByRole('checkbox',{name:'Dispongo de autorización para adjuntar esta evidencia'}).check()
  await page.getByRole('button',{name:'Adjuntar archivo',exact:true}).click()
  await expect(page.getByText('Evidencia adjunta con procedencia y hash')).toBeVisible()
  await page.getByRole('button',{name:'Guardar revisión'}).click()
  await expect(page.getByText('Revisión guardada con historial')).toBeVisible()
  await page.getByRole('link',{name:'Comparar declaraciones',exact:true}).click()
  await page.getByLabel('Comparación',{exact:true}).selectOption(comparisonRun)
  await page.getByRole('checkbox',{name:`Seleccionar comparación ${parcel.padron}`}).check()
  const [exportResponse]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/v1/exports')&&r.request().method()==='POST'),page.getByRole('button',{name:'Exportar selección (1)',exact:true}).click()])
  expect(exportResponse.status()).toBe(202)
  const exports=await exportResponse.json()
  await expect.poll(async()=>(await getJson(`/exports/${exports.job.id}`)).job.status,{timeout:30000,intervals:[1000]}).toBe('COMPLETED')
  const download=await api.get(`/api/v1/exports/${exports.job.id}/download`)
  expect(download.status()).toBe(200)
  const content=await download.text()
  expect(content).toContain('fecha_imagen')
  expect(content).toContain('2025-12')
  expect(content).toContain(parcel.padron)
  expect(content).toContain('CONFIRMADO')
  expect(content).toContain('POSIBLE_CONSTRUCCION_NO_DECLARADA')
  const audit=await getJson('/admin/audit')
  expect(audit.items.some((a:{action:string})=>a.action==='EXPORT_DOWNLOAD')).toBe(true)
  await page.getByRole('link',{name:'Dashboard',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Distribuciones y evolución'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Construcción visible por localidad'})).toBeVisible()
  await page.screenshot({path:'../artifacts/screenshots/dashboard.png',fullPage:true})
})
